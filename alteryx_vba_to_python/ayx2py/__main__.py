"""python -m ayx2py WORKFLOW [OUT_DIR] [--name NAME] [--width N] [--and-before-or] [--spec-only]

Reads an Alteryx workflow (.yxmd, or the same XML saved as .txt) and writes, into OUT_DIR:
    NAME_spec.txt        the logic specification (every rule, each said once)
    NAME_generated.py    Python/pandas code, one function per tool
    ayx_runtime.py       the library the generated code calls
The workflow file is only read. Standard library only.
"""
import argparse
import os
import re
import shutil
import sys

from . import codegen, expr, spec, workflow


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python -m ayx2py", description="Alteryx workflow -> specification + Python.")
    ap.add_argument("workflow")
    ap.add_argument("out_dir", nargs="?", default=None)
    ap.add_argument("--name", default=None, help="prefix of the output files (default: the workflow's name)")
    ap.add_argument("--width", type=int, default=150, help="wrap the specification at N characters (0 = no wrap)")
    ap.add_argument("--and-before-or", action="store_true",
                    help="parse AND before OR instead of Alteryx's documented left-to-right rule")
    ap.add_argument("--spec-only", action="store_true")
    a = ap.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(errors="replace")        # a Windows console may not have every character
    expr.AND_BINDS_TIGHTER = a.and_before_or
    try:
        wf = workflow.Workflow(a.workflow)
    except (workflow.WorkflowError, OSError) as e:
        print("ERROR: %s" % e)
        return 2
    base = a.name or re.sub(r"\W+", "_", os.path.splitext(os.path.basename(a.workflow))[0])
    out_dir = a.out_dir or os.path.join(os.path.dirname(os.path.abspath(a.workflow)), "ayx2py_out")
    if os.path.abspath(out_dir) == os.path.dirname(os.path.abspath(a.workflow)):
        print("ERROR: choose an output folder other than the workflow's own folder")
        return 2
    os.makedirs(out_dir, exist_ok=True)
    lines, info = spec.build(wf, a.width)
    written = []
    path = os.path.join(out_dir, base + "_spec.txt")
    with open(path, "w", encoding="utf-8-sig") as fh:
        fh.write("\n".join(lines) + "\n")
    written.append((path, len(lines), sum(len(x) + 1 for x in lines)))
    if not a.spec_only:
        code, counts = codegen.generate(wf, "Generated by ayx2py from %s (sha256 %s)." % (os.path.basename(a.workflow), wf.sha256))
        path = os.path.join(out_dir, base + "_generated.py")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write("\n".join(code) + "\n")
        written.append((path, len(code), sum(len(x) + 1 for x in code)))
        shutil.copyfile(os.path.join(os.path.dirname(os.path.abspath(__file__)), "ayx_runtime.py"),
                        os.path.join(out_dir, "ayx_runtime.py"))
    end = lines.index("WHAT TO CHECK:") if "WHAT TO CHECK:" in lines else lines.index("INPUTS:")
    print("\n".join(lines[:end]))
    print("repeated sub-chains: %d blocks covering %d tools; rules named once: %d" % (
        len(info["blocks"]), sum(len(c) for b in info["blocks"] for c in b[1:]), len(info["rules"])))
    for p, n, chars in written:
        print("wrote %s: %d lines, %d characters" % (p, n, chars))
    return 0


if __name__ == "__main__":
    sys.exit(main())
